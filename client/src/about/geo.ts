function inside(x: number, y: number, poly: P[]): boolean {
  let o = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) o = !o;
  }
  return o;
}

const K = Math.cos((36 * Math.PI) / 180);
export const MAP_VIEWBOX = '0 0 50.6 37';

export function project(lon: number, lat: number): P {
  return [(lon - 73) * K, 54 - lat];
}

let cache: P[] | null = null;
/** 栅格点（首次调用时计算并缓存） */
export function mapDots(): P[] {
  if (cache) return cache;
  const out: P[] = [];
  const s = 1.05;
  for (let gy = 0.5; gy < 36.5; gy += s) {
    for (let gx = 0.5; gx < 50.6; gx += s) {
      const lon = gx / K + 73;
      const lat = 54 - gy;
      if (inside(lon, lat, CHINA) || inside(lon, lat, HAINAN) || inside(lon, lat, TAIWAN)) out.push([+gx.toFixed(2), +gy.toFixed(2)]);
    }
  }
  cache = out;
  return out;
}

